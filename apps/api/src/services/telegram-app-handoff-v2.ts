/**
 * Versioned Mini App contract, deliberately independent from the opaque th1_
 * token format. A v2 handoff carries a sealed funding *scope*, never calls,
 * signatures, provider quote references, or a funding consent token.
 */
export const TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION = 2 as const;
export const TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION = 2 as const;

const SUPPORTED_CLIENT_ACTION_KINDS = new Set([
  "evm_transaction",
  "evm_transaction_batch",
  "svm_transaction",
  "external_handoff",
] as const);

export type TelegramAppHandoffFundingCapability =
  | Readonly<{ kind: "server_bot_exact" }>
  | Readonly<{
      kind: "web_funding_plan";
      requiredContractVersion: typeof TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION;
    }>
  | Readonly<{ kind: "external_deposit" }>
  | Readonly<{ kind: "unavailable"; reason: string }>;

type SourceDebitScope = Readonly<{
  asset: Money["asset"];
  /**
   * Reservation location for an owned route. A client handoff still retains
   * this identity: its action payload is adapter-owned, but it must not turn a
   * named wallet balance into an unscoped debit allowance.
   */
  locationId: string | null;
  /** Bounded source debit, expressed in the source asset's raw units. */
  maximumRaw: string;
  sourceFingerprint: string;
}>;

type DestinationScope = Readonly<{
  controllerWalletId: string;
  destinationOptionId: string;
  requiredAsset: Money["asset"];
  topology: string;
  venueBindingId: string;
  venueBindingOptionId: string;
  venueId: TelegramAppHandoffV2TradeVenue;
}>;


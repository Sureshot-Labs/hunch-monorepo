function tradeConsumerMatchesSealedPlan(input: {
  plan: TelegramAppHandoffV2FundingPlan;
  reservation: Awaited<
    ReturnType<typeof fetchFundingConsumerReservationForUser>
  >;
}): boolean {
  const consumer = input.plan.funding.discoveryRequest.consumerIntent;
  const reservationConsumer = input.reservation?.consumerIntent;
  return (
    consumer != null &&
    reservationConsumer != null &&
    consumer.venueId === reservationConsumer.venueId &&
    consumer.marketId === reservationConsumer.marketId &&
    consumer.marketContextId === reservationConsumer.marketContextId &&
    consumer.side === reservationConsumer.side &&
    sameAsset(consumer.spend.asset, reservationConsumer.spend.asset) &&
    consumer.spend.raw === reservationConsumer.spend.raw
  );
}

async function resolveReadyTelegramAppHandoffV2TradeContinuation(input: {
  db: Pool;
  handoff: TelegramAppHandoff;
  plan: TelegramAppHandoffV2FundingPlan;
  userId: string;
}): Promise<TelegramAppHandoffV2TradeContinuation | null> {
  return tx(input.db, async (client) => {
    const intentResult = await client.query<{
      funding_operation_id: string | null;
      funding_reservation_id: string | null;
      status: string;
    }>(
      `select intent.funding_operation_id::text,
              intent.funding_reservation_id::text,
              intent.status
         from telegram_trade_intents intent
        where intent.id = $1::uuid
          and intent.user_id = $2::uuid
          and intent.delivery_mode = 'app_handoff'
          and intent.action = 'buy'
        for update`,
      [input.handoff.tradeIntentId, input.userId],
    );
    const intent = intentResult.rows[0];
    if (!intent?.funding_operation_id) return null;
    const reservation = await fetchFundingConsumerReservationForUser(client, {
      forUpdate: true,
      operationId: intent.funding_operation_id,
      userId: input.userId,
    });
    if (!reservation) return null;
    if (!tradeConsumerMatchesSealedPlan({ plan: input.plan, reservation })) {
      throw new TelegramAppHandoffV2Error(
        "trade_intent_changed",
        "ready funding does not match the sealed trade bounds",
      );
    }
    if (
      intent.funding_reservation_id != null &&
      intent.funding_reservation_id !== reservation.reservationId
    ) {
      throw new TelegramAppHandoffV2Error(
        "trade_intent_changed",
        "trade intent is already linked to a different funding reservation",
      );
    }
    if (intent.funding_reservation_id == null) {
      const attached = await client.query(
        `update telegram_trade_intents intent
            set funding_reservation_id = $2::uuid,
                result = coalesce(intent.result, '{}'::jsonb) || jsonb_build_object(
                  'appHandoffFundingReady', jsonb_build_object(
                    'handoffId', $3::uuid,
                    'operationId', $4::uuid,
                    'reservationId', $2::uuid,
                    'version', 2
                  )
                ),
                updated_at = clock_timestamp()
          where intent.id = $1::uuid
            and intent.status = 'funding'
            and intent.funding_operation_id = $4::uuid
            and intent.funding_reservation_id is null`,
        [
          input.handoff.tradeIntentId,
          reservation.reservationId,
          input.handoff.id,
          reservation.operationId,
        ],
      );
      if ((attached.rowCount ?? 0) !== 1) {
        throw new TelegramAppHandoffV2Error(
          "trade_intent_changed",
          "trade intent changed while linking ready funding",
        );
      }
    }
    return {
      fundingOperationId: reservation.operationId,
      fundingReservationId: reservation.reservationId,
      handoffId: input.handoff.id,
      kind: "trade_continuation_required",
      requiredContractVersion:
        TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    };
  });
}

async function resolveTelegramAppHandoffV2TradeTerminal(input: {
  db: Pool;
  handoff: TelegramAppHandoff;
  userId: string;
}): Promise<TelegramAppHandoffV2TradeTerminal | null> {
  const { rows } = await input.db.query<{ status: string }>(
    `select intent.status
       from telegram_trade_intents intent
      where intent.id = $1::uuid
        and intent.user_id = $2::uuid
        and intent.delivery_mode = 'app_handoff'
        and intent.action in ('buy', 'sell')
      limit 1`,
    [input.handoff.tradeIntentId, input.userId],
  );
  const status = rows[0]?.status;
  if (
    status !== "filled" &&
    status !== "failed" &&
    status !== "cancelled" &&
    status !== "expired"
  ) {
    return null;
  }
  return {
    handoffId: input.handoff.id,
    kind: "trade_terminal",
    requiredContractVersion: TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    status,
    tradeIntentId: input.handoff.tradeIntentId,
  };
}

async function resolveTelegramAppHandoffV2TradeInFlight(input: {
  db: Pool;
  handoff: TelegramAppHandoff;
  userId: string;
}): Promise<TelegramAppHandoffV2TradeInFlight | null> {
  const { rows } = await input.db.query<{
    attempt_id: string;
    attempt_state: "accepted" | "ambiguous" | "claimed" | "submission_started";
    funding_operation_id: string;
    funding_reservation_id: string;
  }>(
    `select attempt.id::text as attempt_id,
            attempt.state as attempt_state,
            intent.funding_operation_id::text,
            intent.funding_reservation_id::text
       from telegram_trade_intents intent
       join funding_trade_attempts attempt
         on attempt.user_id = intent.user_id
        and attempt.operation_id = intent.funding_operation_id
        and attempt.reservation_id = intent.funding_reservation_id
      where intent.id = $1::uuid
        and intent.user_id = $2::uuid
        and intent.delivery_mode = 'app_handoff'
        and intent.action = 'buy'
        and intent.result -> 'appHandoffFunding' ->> 'version' = '2'
        and intent.result -> 'appHandoffTradeExecution' ->> 'version' = '2'
        and intent.result -> 'appHandoffTradeExecution' ->> 'attemptId'
          = attempt.id::text
        and attempt.state in (
          'claimed',
          'submission_started',
          'ambiguous',
          'accepted'
        )
      order by attempt.attempt_number desc
      limit 1`,
    [input.handoff.tradeIntentId, input.userId],
  );
  const row = rows[0];
  if (!row) return null;
  return {
    fundingOperationId: row.funding_operation_id,
    fundingReservationId: row.funding_reservation_id,
    handoffId: input.handoff.id,
    kind: "trade_continuation_in_flight",
    requiredContractVersion: TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    tradeAttemptId: row.attempt_id,
    tradeAttemptState: row.attempt_state,
  };
}

/**
 * Read-only v2 execution lookup. This intentionally cannot create or commit
 * funding: only the explicit `/commit` endpoint may cross that boundary.
 */
export async function resolveTelegramAppHandoffV2Execution(input: {
  db: Pool;
  handoff: TelegramAppHandoff;
  userId: string;
}): Promise<TelegramAppHandoffV2Execution> {
  const plan = parseV2Plan(input.handoff.planSnapshot);
  const terminal = await resolveTelegramAppHandoffV2TradeTerminal({
    db: input.db,
    handoff: input.handoff,
    userId: input.userId,
  });
  if (terminal) return terminal;
  if (input.handoff.state !== "committed") {
    throw new TelegramAppHandoffV2Error(
      "handoff_not_committed",
      "funding must be committed before client actions can be prepared",
    );
  }
  if (plan.kind === "direct_trade") {
    const intent = await input.db.query<{
      action: string;
      amount_usd: string | null;
      event_id: string | null;
      market_id: string;
      order_id: string | null;
      side: string | null;
      shares_raw: string | null;
      status: string;
      venue: string;
      venue_order_id: string | null;
    }>(
      `select intent.action,
              intent.amount_usd::text,
              intent.event_id,
              intent.market_id,
              intent.order_id::text,
              intent.side,
              intent.shares_raw,
              intent.status,
              intent.venue,
              intent.venue_order_id
         from telegram_trade_intents intent
        where intent.id = $1::uuid
          and intent.user_id = $2::uuid
          and intent.delivery_mode = 'app_handoff'
          and intent.action in ('buy', 'sell')`,
      [input.handoff.tradeIntentId, input.userId],
    );
    const directIntent = intent.rows[0];
    if (!directIntent || !sealedTradeMatchesIntent(plan.trade, directIntent)) {
      throw new TelegramAppHandoffV2Error(
        "trade_intent_changed",
        "bound direct trade is no longer awaiting the sealed continuation",
      );
    }
    if (
      ["executing", "submitted", "reconcile_required"].includes(
        directIntent.status,
      )
    ) {
      return {
        handoffId: input.handoff.id,
        kind: "direct_trade_in_flight",
        orderId: directIntent.order_id,
        planFingerprint: input.handoff.planFingerprint,
        requiredContractVersion:
          TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
        tradeIntentId: input.handoff.tradeIntentId,
        venueOrderId: directIntent.venue_order_id,
      };
    }
    if (directIntent.status !== "external_handoff") {
      throw new TelegramAppHandoffV2Error(
        "trade_intent_changed",
        "bound direct trade is no longer awaiting the sealed continuation",
      );
    }
    return {
      handoffId: input.handoff.id,
      kind: "direct_trade_continuation_required",
      planFingerprint: input.handoff.planFingerprint,
      requiredContractVersion:
        TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
      tradeIntentId: input.handoff.tradeIntentId,
    };
  }
  const existing = await loadAttachedTelegramAppHandoffV2Funding({
    db: input.db,
    handoffId: input.handoff.id,
    tradeIntentId: input.handoff.tradeIntentId,
    userId: input.userId,
  });
  if (!existing) {
    throw new TelegramAppHandoffV2Error(
      "handoff_not_committed",
      "committed handoff has no attached funding operation",
    );
  }
  const inFlight = await resolveTelegramAppHandoffV2TradeInFlight({
    db: input.db,
    handoff: input.handoff,
    userId: input.userId,
  });
  if (inFlight) return inFlight;
  return (
    (await resolveReadyTelegramAppHandoffV2TradeContinuation({
      db: input.db,
      handoff: input.handoff,
      plan,
      userId: input.userId,
    })) ?? existing
  );
}

/**
 * Claim/commit entrypoint for a v2 Mini App consumer. It is deliberately the
 * only code path that can materialize a sealed funding plan from a th1_ token
 * or release the sealed direct-Buy continuation to its web consumer.
 */
export async function materializeTelegramAppHandoffV2Funding(input: {
  currentAuthorityFingerprint: string;
  currentPolicyRevision: string;
  db: Pool;
  planFingerprint: string;
  runtime: FundingPlanningRuntime;
  telegramUserId: string;
  token: string;
  userId: string;
}): Promise<
  Readonly<{
    execution:
      | MaterializedTelegramAppHandoffV2
      | TelegramAppHandoffV2DirectTradeContinuation;
    handoff: TelegramAppHandoff;
  }>
> {
  // A second Mini App tab can commit between the route-level resolve and this
  // function. Reload before returning so an idempotent response never pairs
  // an existing operation with stale `claimed` handoff state.
  const handoff = await resolveTelegramAppHandoff({
    db: input.db,
    telegramUserId: input.telegramUserId,
    token: input.token,
    userId: input.userId,
  });
  const sealedPlan = parseV2Plan(handoff.planSnapshot);
  if (handoff.state !== "claimed" && handoff.state !== "committed") {
    throw new TelegramAppHandoffV2Error(
      "handoff_not_claimed",
      "handoff must be claimed by the bound Mini App before continuation starts",
    );
  }
  if (input.planFingerprint.trim().toLowerCase() !== handoff.planFingerprint) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed handoff plan changed before funding commit",
    );
  }
  if (
    input.currentPolicyRevision !== handoff.policyRevision ||
    input.currentAuthorityFingerprint.trim().toLowerCase() !==
      handoff.authorityFingerprint
  ) {
    throw new TelegramAppHandoffV2Error(
      "funding_policy_changed",
      "wallet authority or policy changed after Telegram confirmation",
    );
  }
  if (sealedPlan.kind === "direct_trade") {
    return commitTelegramAppHandoffWithExecution({
      commitExecution: async ({ client }) => {
        await assertTelegramAppHandoffV2DirectTradeInTransaction({
          client,
          sealedPlan,
          tradeIntentId: handoff.tradeIntentId,
          userId: input.userId,
        });
        return {
          handoffId: handoff.id,
          kind: "direct_trade_continuation_required" as const,
          planFingerprint: handoff.planFingerprint,
          requiredContractVersion:
            TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
          tradeIntentId: handoff.tradeIntentId,
        };
      },
      committedIntentStatus: "external_handoff",
      executionKind: "direct_trade",
      allowedIntentActions: [
        sealedPlan.trade.action === "sell" ? "sell" : "buy",
      ],
      allowedIntentStatuses: ["previewed", "confirming", "external_handoff"],
      currentAuthorityFingerprint: input.currentAuthorityFingerprint,
      currentPolicyRevision: input.currentPolicyRevision,
      db: input.db,
      planFingerprint: input.planFingerprint,
      telegramUserId: input.telegramUserId,
      token: input.token,
      userId: input.userId,
    });
  }
  const existing = await loadAttachedTelegramAppHandoffV2Funding({
    db: input.db,
    handoffId: handoff.id,
    tradeIntentId: handoff.tradeIntentId,
    userId: input.userId,
  });
  const commitFundingExecution = (
    commitExecution: (
      context: Readonly<{ client: PoolClient }>,
    ) => Promise<MaterializedTelegramAppHandoffV2>,
  ) =>
    commitTelegramAppHandoffWithExecution({
      allowedIntentStatuses: ["funding"],
      commitExecution,
      currentAuthorityFingerprint: input.currentAuthorityFingerprint,
      executionKind: "funding",
      currentPolicyRevision: input.currentPolicyRevision,
      db: input.db,
      planFingerprint: input.planFingerprint,
      telegramUserId: input.telegramUserId,
      token: input.token,
      userId: input.userId,
    });
  if (existing) {
    // Retries still pass through the common commit boundary. Besides keeping
    // the handoff idempotent, this repairs intents created before that boundary
    // started clearing the obsolete `external_handoff_required` marker.
    return commitFundingExecution(async () => existing);
  }
  const prepared = await prepareTelegramAppHandoffV2Funding({
    handoffId: handoff.id,
    planSnapshot: handoff.planSnapshot,
    runtime: input.runtime,
    tradeIntentId: handoff.tradeIntentId,
    userId: input.userId,
  });
  return commitFundingExecution(({ client }) =>
    attachTelegramAppHandoffV2FundingInTransaction(client, {
      handoffId: handoff.id,
      prepared,
      runtime: input.runtime,
      sealedPlan,
      tradeIntentId: handoff.tradeIntentId,
      userId: input.userId,
    }),
  );
}

/** Used by tests and callers to assert the exact public v2 action surface. */
export function telegramAppHandoffV2SupportsActionKind(kind: string): boolean {
  return SUPPORTED_CLIENT_ACTION_KINDS.has(
    kind as typeof SUPPORTED_CLIENT_ACTION_KINDS extends Set<infer T>
      ? T
      : never,
  );
}

/**
 * Select the parser from the declared execution-contract generation, not from
 * whether the v2 body happens to parse. A malformed v2 object must fail closed
 * rather than be interpreted as the old callback-replay handoff.
 */
export function telegramAppHandoffPlanGeneration(
  snapshot: JsonObject,
): "legacy" | "unsupported" | "v2" {
  if (snapshot.version === TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION) return "v2";
  return snapshot.version == null || snapshot.version === 1
    ? "legacy"
    : "unsupported";
}


/**
 * A returned in-flight or terminal state is observational only.  The caller
 * must not re-check live authority before showing it: that authority gates
 * the next action, not visibility into an action that was already claimed.
 */
export function isTelegramAppHandoffV2ReadOnlyExecution(
  execution: TelegramAppHandoffV2Execution,
): boolean {
  return (
    execution.kind === "direct_trade_in_flight" ||
    execution.kind === "trade_continuation_in_flight" ||
    execution.kind === "trade_terminal"
  );
}

export class TelegramAppHandoffV2Error extends Error {
  constructor(
    readonly code:
      | "contract_unsupported"
      | "destination_changed"
      | "funding_policy_changed"
      | "handoff_not_claimed"
      | "handoff_not_committed"
      | "plan_invalid"
      | "source_scope_changed"
      | "trade_intent_changed",
    message: string,
  ) {
    super(message);
    this.name = "TelegramAppHandoffV2Error";
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function isJsonObject(value: unknown): value is JsonObject {
  return isRecord(value);
}

function exactAsset(value: unknown): Money["asset"] | null {
  if (!isRecord(value)) return null;
  const { assetId, decimals, networkId } = value;
  return typeof assetId === "string" &&
    typeof networkId === "string" &&
    typeof decimals === "number" &&
    Number.isInteger(decimals) &&
    decimals >= 0 &&
    decimals <= 255
    ? { assetId, decimals, networkId }
    : null;
}

function exactMoney(value: unknown): Money | null {
  if (!isRecord(value)) return null;
  const asset = exactAsset(value.asset);
  return asset && isRawAmount(value.raw) ? { asset, raw: value.raw } : null;
}

function sameAsset(left: Money["asset"], right: Money["asset"]): boolean {
  return (
    left.networkId === right.networkId &&
    left.assetId.toLowerCase() === right.assetId.toLowerCase() &&
    left.decimals === right.decimals
  );
}

function actionShape(
  actions: readonly Readonly<{
    actor: "server" | "user";
    kind: string;
    valueMoving: boolean;
  }>[],
): readonly Readonly<{
  actor: "server" | "user";
  kind: string;
  valueMoving: boolean;
}>[] {
  return [...actions]
    .map((action) => ({
      actor: action.actor,
      kind: action.kind,
      valueMoving: action.valueMoving,
    }))
    .sort((left, right) =>
      `${left.kind}:${left.actor}:${left.valueMoving}`.localeCompare(
        `${right.kind}:${right.actor}:${right.valueMoving}`,
      ),
    );
}

function sourceIdentity(
  source: SourceOption["source"] | SourceOptionLeg["source"],
): JsonObject | null {
  if (source.kind === "owned_location") {
    return {
      asset: source.location.asset,
      locationId: source.location.locationId,
      kind: source.kind,
    };
  }
  if (source.kind === "external_ingress" && source.controlledSender) {
    return {
      asset: source.asset,
      ingressKind: source.ingressKind,
      kind: source.kind,
      networkId: source.networkId,
    };
  }
  return null;
}

function sourceScope(input: {
  actions: SourceOption["requiredActions"];
  amount: Money;
  maximumSourceDebitSlippageBps: number;
  source: SourceOption["source"] | SourceOptionLeg["source"];
}): SourceDebitScope | null {
  const identity = sourceIdentity(input.source);
  if (!identity) return null;
  const maximumRaw =
    (rawAmount(input.amount.raw) *
      BigInt(10_000 + input.maximumSourceDebitSlippageBps) +
      9_999n) /
    10_000n;
  return {
    asset: input.amount.asset,
    locationId:
      input.source.kind === "owned_location"
        ? input.source.location.locationId
        : null,
    maximumRaw: maximumRaw.toString(),
    sourceFingerprint: canonicalJsonHash({
      actions: actionShape(input.actions),
      source: identity,
    }),
  };
}

function quotedOptionSourceAmount(option: SourceOption): Money | null {
  const sourceAsset =
    option.source.kind === "owned_location"
      ? option.source.location.asset
      : option.source.kind === "external_ingress"
        ? option.source.asset
        : null;
  if (!sourceAsset) return null;
  const amount =
    option.quotedSourceAmount ??
    (option.maximumSourceRaw
      ? { asset: sourceAsset, raw: option.maximumSourceRaw }
      : null);
  return amount && sameAsset(amount.asset, sourceAsset) ? amount : null;
}

function optionSourceScopes(
  option: SourceOption,
  maximumSourceDebitSlippageBps = 0,
): readonly SourceDebitScope[] | null {
  if (option.source.kind === "composite") {
    const legs = option.sourceLegs;
    if (!legs || legs.length === 0) return null;
    const scopes = legs.map((leg) =>
      sourceScope({
        actions: leg.requiredActions,
        amount: leg.sourceAmount,
        maximumSourceDebitSlippageBps,
        source: leg.source,
      }),
    );
    return scopes.every((scope): scope is SourceDebitScope => scope != null)
      ? scopes
      : null;
  }
  const amount = quotedOptionSourceAmount(option);
  if (!amount) return null;
  // `maximumSourceRaw` is already a capacity boundary when an adapter has no
  // exact quote. Only a genuine quoted debit may move inside the confirmed
  // re-quote tolerance; inflating capacity would authorize unavailable funds.
  const quotedDebitSlippageBps = option.quotedSourceAmount
    ? maximumSourceDebitSlippageBps
    : 0;
  const scopes = [
    sourceScope({
      actions: option.requiredActions,
      amount,
      maximumSourceDebitSlippageBps: quotedDebitSlippageBps,
      source: option.source,
    }),
  ].filter((scope): scope is SourceDebitScope => scope != null);
  return scopes.length > 0 ? scopes : null;
}

function sourceScopeKey(scope: SourceDebitScope): string {
  return [
    scope.asset.networkId,
    scope.asset.assetId.toLowerCase(),
    String(scope.asset.decimals),
    scope.locationId ?? scope.sourceFingerprint,
  ].join(":");
}

/** A source may appear in more than one selectable route; its sealed cap is
 * the highest bound the bot explicitly permitted, never a sum of alternatives. */
function dedupeSourceScopes(
  scopes: readonly SourceDebitScope[],
): readonly SourceDebitScope[] {
  const bySource = new Map<string, SourceDebitScope>();
  for (const scope of scopes) {
    const key = sourceScopeKey(scope);
    const existing = bySource.get(key);
    if (
      !existing ||
      rawAmount(scope.maximumRaw) > rawAmount(existing.maximumRaw)
    ) {
      bySource.set(key, scope);
    }
  }
  return [...bySource.values()];
}

function hasUnsupportedClientAction(option: SourceOption): boolean {
  return option.requiredActions.some(
    (action) =>
      // V2 is a client execution contract. A generic plan carrying a server
      // action would need a second, implicit authority path, so reject it
      // rather than treating its kind as something the Mini App can execute.
      action.actor !== "user" ||
      action.kind === "signature" ||
      !SUPPORTED_CLIENT_ACTION_KINDS.has(
        action.kind as typeof SUPPORTED_CLIENT_ACTION_KINDS extends Set<infer T>
          ? T
          : never,
      ),
  );
}

function hasVenuePreparationSource(option: SourceOption): boolean {
  return (
    option.source.kind === "venue_preparation" ||
    option.sourceLegs?.some(
      (leg) => leg.source.kind === "venue_preparation",
    ) === true
  );
}

function isInteractiveExternalDeposit(option: SourceOption): boolean {
  return (
    option.source.kind === "external_ingress" && !option.source.controlledSender
  );
}

function sourceOptionFeeCapUsd(option: SourceOption): string | null {
  const fees = option.fees.map((fee) => fee.estimatedUsd);
  return fees.every((fee): fee is string => fee != null)
    ? addUnsignedDecimals(fees)
    : null;
}

function isSealableClientFundingOption(option: SourceOption): boolean {
  return (
    // A venue-preparation option owns several physical input reservations but
    // exposes no one client-debit identity. Do not seal it until its adapter
    // can provide the same exact locations a generic materialized plan uses.
    !hasVenuePreparationSource(option) &&
    !hasUnsupportedClientAction(option) &&
    !isInteractiveExternalDeposit(option) &&
    optionSourceScopes(option) != null &&
    sourceOptionFeeCapUsd(option) != null
  );
}

function maximumSealedFundingFeeUsd(
  options: readonly SourceOption[],
  maximumSlippageBps: number,
): string | null {
  let maximum: string | null = null;
  for (const option of options) {
    const cap = sourceOptionFeeCapUsd(option);
    if (cap == null) continue;
    if (maximum == null || compareUnsignedDecimals(cap, maximum) > 0) {
      maximum = cap;
    }
  }
  return maximum == null
    ? null
    : multiplyUnsignedDecimals(
        maximum,
        formatUnsignedDecimal(BigInt(10_000 + maximumSlippageBps), 4),
      );
}

function destinationScope(option: FundingDestinationOption): DestinationScope {
  if (!isTelegramAppHandoffV2TradeVenue(option.venueId)) {
    throw new TelegramAppHandoffV2Error(
      "destination_changed",
      "sealed handoff destination venue is unsupported",
    );
  }
  return {
    controllerWalletId: option.controllerWalletId,
    destinationOptionId: option.destinationOptionId,
    requiredAsset: option.requiredAsset,
    topology: option.topology,
    venueBindingId: option.venueBindingId,
    venueBindingOptionId: option.venueBindingOptionId,
    venueId: option.venueId,
  };
}

function sameDestinationScope(
  left: DestinationScope,
  right: FundingDestinationOption,
): boolean {
  return (
    left.controllerWalletId === right.controllerWalletId &&
    left.destinationOptionId === right.destinationOptionId &&
    left.topology === right.topology &&
    left.venueBindingId === right.venueBindingId &&
    left.venueBindingOptionId === right.venueBindingOptionId &&
    left.venueId === right.venueId &&
    sameAsset(left.requiredAsset, right.requiredAsset)
  );
}

/**
 * Capability is derived from a real generic projection, not from a venue or
 * chain boolean. `external_deposit` remains interactive: it must not be
 * advertised as an auto-close Mini App execution plan.
 */
export function resolveTelegramAppHandoffFundingCapability(input: {
  projection: IntentLiquidityProjection;
  serverBotExact: boolean;
}): TelegramAppHandoffFundingCapability {
  if (input.serverBotExact) return { kind: "server_bot_exact" };
  const options = input.projection.sourceOptions.filter(
    (option) => option.selectable,
  );
  if (options.some(isSealableClientFundingOption)) {
    return {
      kind: "web_funding_plan",
      requiredContractVersion:
        TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    };
  }
  if (options.some(isInteractiveExternalDeposit)) {
    return { kind: "external_deposit" };
  }
  return { kind: "unavailable", reason: "no_supported_owned_source" };
}

/** Creates a sealed v2 plan from a server-produced generic liquidity result. */
export function buildTelegramAppHandoffV2Plan(input: {
  discoveryRequest: FundingDiscoveryRequest;
  fundingPolicyRevision: string;
  projection: IntentLiquidityProjection;
  trade: JsonObject;
}): TelegramAppHandoffV2FundingPlan {
  const destination = input.projection.destinationOptions.find(
    (option) =>
      option.selectable &&
      option.destinationOptionId === input.projection.destinationOptionId,
  );
  if (!destination) {
    throw new TelegramAppHandoffV2Error(
      "destination_changed",
      "sealed handoff lacks a selectable destination",
    );
  }
  const selectableSources = input.projection.sourceOptions.filter(
    (option) => option.selectable && isSealableClientFundingOption(option),
  );
  const maximumSlippageBps = input.discoveryRequest.maxSlippageBps ?? 0;
  const sourceDebits = dedupeSourceScopes(
    selectableSources.flatMap(
      (option) => optionSourceScopes(option, maximumSlippageBps) ?? [],
    ),
  );
  if (sourceDebits.length === 0) {
    throw new TelegramAppHandoffV2Error(
      "source_scope_changed",
      "sealed handoff lacks a supported owned source",
    );
  }
  const quotedFundingFeeCap = maximumSealedFundingFeeUsd(
    selectableSources,
    maximumSlippageBps,
  );
  if (quotedFundingFeeCap == null) {
    throw new TelegramAppHandoffV2Error(
      "source_scope_changed",
      "sealed handoff lacks an exact funding fee bound",
    );
  }
  const existingFeeCap = input.discoveryRequest.maxFeeUsd;
  const maxFeeUsd =
    existingFeeCap != null &&
    compareUnsignedDecimals(existingFeeCap, quotedFundingFeeCap) < 0
      ? existingFeeCap
      : quotedFundingFeeCap;
  const plan: TelegramAppHandoffV2Plan = {
    executionContractVersion:
      TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    funding: {
      discoveryRequest: {
        ...input.discoveryRequest,
        maxFeeUsd,
      },
      destination: destinationScope(destination),
      fundingPolicyRevision: input.fundingPolicyRevision,
      sourceDebits,
    },
    kind: "funding",
    trade: input.trade,
    version: TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION,
  };
  // Keep the producer and consumer contract identical: no caller can issue a
  // v2 token whose own materializer would later reject its sealed trade scope.
  return parseV2FundingPlan(plan);
}

/** Creates a sealed v2 handoff for one exact direct Buy or Sell. */
export function buildTelegramAppHandoffV2DirectTradePlan(input: {
  /** The verified controller which may submit this one sealed direct trade. */
  controllerWalletAddress: string;
  trade: JsonObject;
}): TelegramAppHandoffV2DirectTradePlan {
  const controllerWalletAddress = input.controllerWalletAddress.trim();
  if (!/^0x[0-9a-f]{40}$/iu.test(controllerWalletAddress)) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed direct trade controller is malformed",
    );
  }
  const plan = parseV2Plan({
    executionContractVersion:
      TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    kind: "direct_trade",
    trade: {
      ...input.trade,
      controllerWalletAddress: controllerWalletAddress.toLowerCase(),
    },
    version: TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION,
  });
  if (plan.kind !== "direct_trade") {
    throw new Error("direct handoff builder returned a funding plan");
  }
  return plan;
}

function parseV2Plan(snapshot: JsonObject): TelegramAppHandoffV2Plan {
  if (
    snapshot.version !== TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION ||
    snapshot.executionContractVersion !==
      TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION ||
    !isJsonObject(snapshot.trade) ||
    (snapshot.kind !== "funding" && snapshot.kind !== "direct_trade")
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed handoff is not execution-contract v2",
    );
  }
  const trade = snapshot.trade;
  const action = trade.action;
  if (
    (action !== "buy" && action !== "sell") ||
    !isTelegramAppHandoffV2TradeVenue(trade.venue) ||
    (trade.side !== "YES" && trade.side !== "NO") ||
    typeof trade.marketId !== "string" ||
    !trade.marketId ||
    typeof trade.outcomeTokenId !== "string" ||
    !trade.outcomeTokenId ||
    !(typeof trade.eventId === "string" || trade.eventId === null) ||
    typeof trade.maxSlippageBps !== "number" ||
    !Number.isInteger(trade.maxSlippageBps) ||
    trade.maxSlippageBps < 0
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed trade scope is malformed",
    );
  }
  if (
    (action === "buy" &&
      (typeof trade.amountUsd !== "number" ||
        !Number.isFinite(trade.amountUsd) ||
        trade.amountUsd <= 0 ||
        typeof trade.maxSpendUsd !== "number" ||
        !Number.isFinite(trade.maxSpendUsd) ||
        trade.maxSpendUsd < trade.amountUsd)) ||
    (action === "sell" &&
      (!isRawAmount(trade.sharesRaw) ||
        !isRawAmount(trade.minimumReceiveRaw) ||
        BigInt(trade.sharesRaw) <= 0n ||
        BigInt(trade.minimumReceiveRaw) <= 0n))
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed trade economic bounds are malformed",
    );
  }
  // A v2 handoff always names the one controller allowed to consume its
  // funding reservation or submit its direct Buy.  Funding and direct plans
  // use the same trade boundary; keeping it here prevents one from silently
  // becoming less constrained than the other.
  if (
    typeof trade.controllerWalletAddress !== "string" ||
    !/^0x[0-9a-f]{40}$/iu.test(trade.controllerWalletAddress)
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed trade controller is malformed",
    );
  }
  if (snapshot.kind === "direct_trade") {
    if (!isTelegramAppHandoffV2DirectTradeVenue(trade.venue)) {
      throw new TelegramAppHandoffV2Error(
        "plan_invalid",
        "sealed direct trade venue is unsupported",
      );
    }
    return {
      executionContractVersion:
        TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
      kind: "direct_trade",
      trade,
      version: TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION,
    };
  }
  const funding = snapshot.funding;
  if (action !== "buy") {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed Sell cannot contain a funding plan",
    );
  }
  if (
    !isRecord(funding) ||
    !isJsonObject(funding.discoveryRequest) ||
    !isRecord(funding.destination) ||
    !Array.isArray(funding.sourceDebits) ||
    typeof funding.fundingPolicyRevision !== "string" ||
    !funding.fundingPolicyRevision
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed funding scope is malformed",
    );
  }
  const destinationAsset = exactAsset(funding.destination.requiredAsset);
  if (
    !destinationAsset ||
    typeof funding.destination.controllerWalletId !== "string" ||
    typeof funding.destination.destinationOptionId !== "string" ||
    typeof funding.destination.topology !== "string" ||
    typeof funding.destination.venueBindingId !== "string" ||
    typeof funding.destination.venueBindingOptionId !== "string" ||
    !isTelegramAppHandoffV2TradeVenue(funding.destination.venueId) ||
    funding.destination.venueId !== trade.venue
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed funding destination is malformed",
    );
  }
  const sourceDebits = funding.sourceDebits.map((value) => {
    if (!isRecord(value)) {
      throw new TelegramAppHandoffV2Error(
        "plan_invalid",
        "sealed funding source is malformed",
      );
    }
    const asset = exactAsset(value.asset);
    if (
      !asset ||
      !isRawAmount(value.maximumRaw) ||
      !(typeof value.locationId === "string" || value.locationId === null) ||
      typeof value.sourceFingerprint !== "string" ||
      !/^[0-9a-f]{64}$/iu.test(value.sourceFingerprint)
    ) {
      throw new TelegramAppHandoffV2Error(
        "plan_invalid",
        "sealed funding source is malformed",
      );
    }
    return {
      asset,
      locationId: value.locationId,
      maximumRaw: value.maximumRaw,
      sourceFingerprint: value.sourceFingerprint.toLowerCase(),
    };
  });
  if (sourceDebits.length === 0) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed funding scope has no sources",
    );
  }
  const { serverAdditionalDestinationAmount, ...publicDiscoveryRequest } =
    funding.discoveryRequest;
  const additionalDestination =
    serverAdditionalDestinationAmount === undefined
      ? null
      : exactMoney(serverAdditionalDestinationAmount);
  const request = fundingDiscoveryRequestSchema.safeParse(
    publicDiscoveryRequest,
  );
  if (!request.success || request.data.purpose !== "trade_shortfall") {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed handoff may only materialize a client funding plan",
    );
  }
  if (
    serverAdditionalDestinationAmount !== undefined &&
    !additionalDestination
  ) {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "sealed additional funding amount is malformed",
    );
  }
  return {
    executionContractVersion:
      TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    funding: {
      discoveryRequest: {
        ...request.data,
        ...(additionalDestination
          ? { serverAdditionalDestinationAmount: additionalDestination }
          : {}),
      },
      destination: {
        controllerWalletId: funding.destination.controllerWalletId,
        destinationOptionId: funding.destination.destinationOptionId,
        requiredAsset: destinationAsset,
        topology: funding.destination.topology,
        venueBindingId: funding.destination.venueBindingId,
        venueBindingOptionId: funding.destination.venueBindingOptionId,
        venueId: funding.destination.venueId,
      },
      fundingPolicyRevision: funding.fundingPolicyRevision,
      sourceDebits,
    },
    kind: "funding",
    trade,
    version: TELEGRAM_APP_HANDOFF_V2_PLAN_VERSION,
  };
}

function parseV2FundingPlan(
  snapshot: JsonObject,
): TelegramAppHandoffV2FundingPlan {
  const plan = parseV2Plan(snapshot);
  if (plan.kind !== "funding") {
    throw new TelegramAppHandoffV2Error(
      "plan_invalid",
      "this handoff has no funding plan",
    );
  }
  return plan;
}

function sealedTradeMatchesIntent(
  trade: JsonObject,
  intent: Readonly<{
    action: string;
    amount_usd: string | null;
    event_id: string | null;
    market_id: string;
    shares_raw?: string | null;
    side: string | null;
    venue: string;
  }>,
): boolean {
  const common =
    trade.action === intent.action &&
    trade.venue === intent.venue &&
    trade.marketId === intent.market_id &&
    trade.eventId === intent.event_id &&
    trade.side === intent.side;
  if (!common) return false;
  if (trade.action === "sell") {
    return (
      typeof trade.sharesRaw === "string" &&
      intent.shares_raw != null &&
      trade.sharesRaw === intent.shares_raw
    );
  }
  const sealedAmount = trade.amountUsd;
  return (
    typeof sealedAmount === "number" &&
    Number.isFinite(sealedAmount) &&
    intent.amount_usd != null &&
    Number(intent.amount_usd) === sealedAmount
  );
}


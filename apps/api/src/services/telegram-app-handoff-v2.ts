/**
 * A v2 handoff scopes an owned source by its stable reservation location and
 * exact asset.  Old snapshots included the then-current action shape in their
 * fingerprint, so matching that field would turn a harmless fresh-plan setup
 * change into a false `source_scope_changed`.  Null-location ingress remains
 * fingerprint-bound because it has no durable reservation location.
 */
export function telegramAppHandoffV2SourceOptionWithinScope(
  sealed: readonly SourceDebitScope[],
  option: SourceOption,
): boolean {
  const current = optionSourceScopes(option);
  if (!current || current.length === 0) return false;
  return current.every((entry) =>
    sealed.some((candidate) => {
      if (!sameAsset(candidate.asset, entry.asset)) return false;
      if (candidate.locationId !== null || entry.locationId !== null) {
        return (
          candidate.locationId !== null &&
          entry.locationId !== null &&
          candidate.locationId === entry.locationId
        );
      }
      return candidate.sourceFingerprint === entry.sourceFingerprint;
    }),
  );
}

type PreparedOwnedSource = Readonly<{
  kind: "owned_location";
  location: Readonly<{
    asset: Money["asset"];
    details: Readonly<Record<string, unknown>>;
    locationId: string;
  }>;
}>;

function preparedOwnedSource(value: unknown): PreparedOwnedSource | null {
  if (!isRecord(value) || value.kind !== "owned_location") return null;
  const location = isRecord(value.location) ? value.location : null;
  const asset = location ? exactAsset(location.asset) : null;
  const details =
    location && isRecord(location.details) ? location.details : null;
  return location && asset && details && typeof location.locationId === "string"
    ? {
        kind: "owned_location",
        location: { asset, details, locationId: location.locationId },
      }
    : null;
}

function preparedOwnedSources(
  value: unknown,
): readonly PreparedOwnedSource[] | null {
  if (!isRecord(value) || !isRecord(value.source)) return null;
  const composite = value.kind === "composite";
  const compositeSource = value.source.kind === "composite";
  const legs = Array.isArray(value.sourceLegs) ? value.sourceLegs : null;
  if (composite || compositeSource || legs) {
    if (
      !composite ||
      !compositeSource ||
      !legs ||
      !Number.isInteger(value.source.legCount) ||
      value.source.legCount !== legs.length
    ) {
      return null;
    }
    const owned: PreparedOwnedSource[] = [];
    for (const leg of legs) {
      if (!isRecord(leg) || !isRecord(leg.source)) return null;
      if (leg.source.kind === "owned_location") {
        const source = preparedOwnedSource(leg.source);
        if (!source) return null;
        owned.push(source);
      } else if (
        leg.source.kind !== "external_ingress" &&
        leg.source.kind !== "venue_preparation"
      ) {
        return null;
      }
    }
    return owned;
  }
  if (value.source.kind === "owned_location") {
    const source = preparedOwnedSource(value.source);
    return source ? [source] : null;
  }
  return value.source.kind === "external_ingress" ||
    value.source.kind === "venue_preparation"
    ? []
    : null;
}

function preparedOwnedSourceKey(
  asset: Money["asset"],
  reservationLocationId: string,
): string {
  return [
    asset.networkId,
    asset.assetId.toLowerCase(),
    String(asset.decimals),
    reservationLocationId,
  ].join(":");
}

function preparedPlanWithinSourceScope(
  input: Readonly<{
    prepared: PreparedFundingRuntimeCommit;
    sealedSources: readonly SourceDebitScope[];
  }>,
): boolean {
  const reservations = input.prepared.operation.quote.planSnapshot.reservations;
  const debits = reservations.filter(
    (reservation) => reservation.mode === "subtract_available",
  );
  if (debits.length === 0) {
    const operation = input.prepared.operation.quote.planSnapshot.operation;
    const requested = operation.requestedSourceAmount;
    const requestedAsset =
      requested && isRecord(requested) ? exactAsset(requested.asset) : null;
    const requestedRaw =
      requested && isRecord(requested) ? requested.raw : null;
    return (
      operation.planKind === "direct_external_handoff" &&
      requestedAsset != null &&
      isRawAmount(requestedRaw) &&
      input.prepared.operation.quote.planSnapshot.steps.some(
        (step) => step.normalizedAction.kind === "external_handoff",
      ) &&
      input.sealedSources.some(
        (source) =>
          source.locationId === null &&
          sameAsset(source.asset, requestedAsset) &&
          rawAmount(requestedRaw) <= rawAmount(source.maximumRaw),
      )
    );
  }
  const ownedSources = preparedOwnedSources(
    input.prepared.operation.quote.selectedSourceOptionSnapshot,
  );
  if (!ownedSources || ownedSources.length === 0) return false;
  const totals = new Map<string, bigint>();
  const maximums = new Map<string, bigint>();
  for (const debit of debits) {
    const asset = {
      assetId: debit.assetId,
      decimals: debit.assetDecimals,
      networkId: debit.networkId,
    };
    // A debit reservation must name its physical location. A null scoped
    // source is an exact external handoff and is allowed only in the zero-
    // reservation branch above; it must never authorize an arbitrary debit.
    const matchingOwnedSources = ownedSources.filter(
      (ownedSource) =>
        sameAsset(ownedSource.location.asset, asset) &&
        fundingOwnedSourceIncludesLocation(ownedSource, debit.locationId),
    );
    const reservationLocationIds = [
      ...new Set(
        matchingOwnedSources
          .map(fundingOwnedSourceReservationLocationId)
          .filter((locationId): locationId is string => locationId != null),
      ),
    ];
    if (reservationLocationIds.length !== 1) return false;
    const matchingSealedSources = input.sealedSources.filter(
      (candidate) =>
        candidate.locationId !== null &&
        sameAsset(candidate.asset, asset) &&
        matchingOwnedSources.some((ownedSource) =>
          fundingOwnedSourceIncludesLocation(
            ownedSource,
            candidate.locationId as string,
          ),
        ),
    );
    if (matchingSealedSources.length === 0) return false;
    const maximumRaw = matchingSealedSources.reduce((maximum, source) => {
      const candidate = rawAmount(source.maximumRaw);
      return candidate > maximum ? candidate : maximum;
    }, 0n);
    const key = preparedOwnedSourceKey(asset, reservationLocationIds[0]);
    totals.set(key, (totals.get(key) ?? 0n) + rawAmount(debit.rawAmount));
    maximums.set(key, maximumRaw);
  }
  return [...totals.entries()].every(
    ([key, total]) => total <= (maximums.get(key) ?? -1n),
  );
}

function preparedPlanMatchesDestinationScope(
  input: Readonly<{
    prepared: PreparedFundingRuntimeCommit;
    destination: DestinationScope;
  }>,
): boolean {
  const operation = input.prepared.operation.quote.planSnapshot.operation;
  const target = operation.destinationTargetSnapshot;
  const binding = operation.venueBindingSnapshot;
  if (!isRecord(target) || !isRecord(target.location) || !isRecord(binding)) {
    return false;
  }
  const location = target.location;
  const details = isRecord(location.details) ? location.details : null;
  const asset = exactAsset(location.asset);
  return (
    target.kind === "owned_location" &&
    operation.venueId === input.destination.venueId &&
    binding.venueBindingOptionId === input.destination.venueBindingOptionId &&
    details?.controllerWalletId === input.destination.controllerWalletId &&
    asset != null &&
    sameAsset(asset, input.destination.requiredAsset)
  );
}

function selectScopedSource(
  projection: IntentLiquidityProjection,
  sourceDebits: readonly SourceDebitScope[],
): SourceOption | null {
  return (
    projection.sourceOptions.find(
      (option) =>
        option.selectable &&
        isSealableClientFundingOption(option) &&
        telegramAppHandoffV2SourceOptionWithinScope(sourceDebits, option) &&
        option.recommended,
    ) ??
    projection.sourceOptions.find(
      (option) =>
        option.selectable &&
        isSealableClientFundingOption(option) &&
        telegramAppHandoffV2SourceOptionWithinScope(sourceDebits, option),
    ) ??
    null
  );
}

export function telegramAppHandoffV2FundingIdempotencyKey(
  handoffId: string,
): string {
  return `telegram-app-handoff:${handoffId}:funding`;
}

/**
 * The intent link is only a convenience pointer. These facts bind it to one
 * sealed v2 handoff and prevent a retry from inheriting unrelated funding.
 */
export function isTelegramAppHandoffV2FundingBinding(input: {
  handoffId: string;
  operationId: string;
  result: unknown;
}): boolean {
  if (!isRecord(input.result) || !isRecord(input.result.appHandoffFunding)) {
    return false;
  }
  const binding = input.result.appHandoffFunding;
  return (
    binding.version === 2 &&
    binding.handoffId === input.handoffId &&
    binding.operationId === input.operationId
  );
}

/**
 * Replans only inside the immutable v2 source/destination envelope. The
 * runtime remains the sole quote and operation builder; this layer supplies
 * the sealed owner boundary and verifies its output before durable commit.
 */
export async function prepareTelegramAppHandoffV2Funding(input: {
  handoffId: string;
  planSnapshot: JsonObject;
  runtime: FundingPlanningRuntime;
  tradeIntentId: string;
  userId: string;
}): Promise<PreparedFundingRuntimeCommit> {
  const plan = parseV2FundingPlan(input.planSnapshot);
  if (
    (await input.runtime.currentPolicyRevision()) !==
    plan.funding.fundingPolicyRevision
  ) {
    throw new TelegramAppHandoffV2Error(
      "funding_policy_changed",
      "funding policy changed after Telegram confirmation",
    );
  }
  // A Telegram quote expiry protects the bot-card confirmation. The sealed
  // handoff has its own TTL and re-quotes funding inside its immutable bounds,
  // so materialization must use the current funding-policy quote window.
  const currentRequest: FundingDiscoveryRequest = {
    ...plan.funding.discoveryRequest,
    deadline: null,
    destinationOptionId: plan.funding.destination.destinationOptionId,
    venueBindingOptionId: plan.funding.destination.venueBindingOptionId,
  };
  const projection = await input.runtime.liquidity(
    input.userId,
    currentRequest,
  );
  const currentDestination = projection.destinationOptions.find((option) =>
    sameDestinationScope(plan.funding.destination, option),
  );
  if (
    !currentDestination ||
    !currentDestination.selectable ||
    projection.destinationOptionId !==
      plan.funding.destination.destinationOptionId
  ) {
    throw new TelegramAppHandoffV2Error(
      "destination_changed",
      "funding destination or controller changed",
    );
  }
  const selected = selectScopedSource(projection, plan.funding.sourceDebits);
  if (!selected) {
    throw new TelegramAppHandoffV2Error(
      "source_scope_changed",
      "no current route fits the sealed source scope",
    );
  }
  const quoteRequest: FundingQuoteRequest = {
    confirmedSourceAmount: null,
    liquidityProjectionId: projection.liquidityProjectionId,
    // The sealed trade amount remains the later Buy ceiling. Funding quotes
    // cover only the exact additional destination credit still required now.
    requestedDestinationAmount:
      fundingDestinationAmountForRequest(currentRequest),
    selectedSourceOptionId: selected.sourceOptionId,
  };
  const quote = await input.runtime.quoteForCommitScope(
    input.userId,
    quoteRequest,
    {
      kind: "telegram_app_handoff_v2",
      handoffId: input.handoffId,
      tradeIntentId: input.tradeIntentId,
    },
  );
  const prepared = await input.runtime.prepareCommit(
    input.userId,
    {
      consentToken: quote.consentToken,
      idempotencyKey: telegramAppHandoffV2FundingIdempotencyKey(
        input.handoffId,
      ),
      quoteId: quote.quoteId,
    },
    {
      commitScope: {
        kind: "telegram_app_handoff_v2",
        handoffId: input.handoffId,
        tradeIntentId: input.tradeIntentId,
      },
    },
  );
  if (
    !preparedPlanWithinSourceScope({
      prepared,
      sealedSources: plan.funding.sourceDebits,
    })
  ) {
    throw new TelegramAppHandoffV2Error(
      "source_scope_changed",
      "fresh funding plan exceeds the sealed source scope",
    );
  }
  if (
    !preparedPlanMatchesDestinationScope({
      prepared,
      destination: plan.funding.destination,
    })
  ) {
    throw new TelegramAppHandoffV2Error(
      "destination_changed",
      "fresh funding plan differs from the sealed destination scope",
    );
  }
  return prepared;
}

export async function attachTelegramAppHandoffV2FundingInTransaction(
  client: PoolClient,
  input: Readonly<{
    handoffId: string;
    prepared: PreparedFundingRuntimeCommit;
    runtime: FundingPlanningRuntime;
    sealedPlan: TelegramAppHandoffV2FundingPlan;
    tradeIntentId: string;
    userId: string;
  }>,
): Promise<MaterializedTelegramAppHandoffV2> {
  const existing = await client.query<{
    action: string;
    amount_usd: string | null;
    event_id: string | null;
    funding_operation_id: string | null;
    market_id: string;
    result: unknown;
    side: string | null;
    venue: string;
  }>(
    `select intent.action,
            intent.amount_usd::text,
            intent.event_id,
            intent.funding_operation_id::text,
            intent.market_id,
            intent.result,
            intent.side,
            intent.venue
       from telegram_trade_intents intent
      where intent.id = $1::uuid
        and intent.user_id = $2::uuid
        and intent.delivery_mode = 'app_handoff'
        and intent.action = 'buy'
      for update`,
    [input.tradeIntentId, input.userId],
  );
  const intent = existing.rows[0];
  if (!intent) {
    throw new TelegramAppHandoffV2Error(
      "trade_intent_changed",
      "bound trade intent no longer belongs to this handoff",
    );
  }
  if (!sealedTradeMatchesIntent(input.sealedPlan.trade, intent)) {
    throw new TelegramAppHandoffV2Error(
      "trade_intent_changed",
      "bound trade intent differs from the sealed handoff scope",
    );
  }
  if (intent.funding_operation_id) {
    if (
      !isTelegramAppHandoffV2FundingBinding({
        handoffId: input.handoffId,
        operationId: intent.funding_operation_id,
        result: intent.result,
      })
    ) {
      throw new TelegramAppHandoffV2Error(
        "trade_intent_changed",
        "trade intent is linked to funding from a different handoff",
      );
    }
    const operation = await client.query<{ id: string }>(
      `select operation_row.id::text
         from funding_operations operation_row
        where operation_row.id = $1::uuid
          and operation_row.user_id = $2::uuid
          and operation_row.idempotency_key = $3
        for key share`,
      [
        intent.funding_operation_id,
        input.userId,
        telegramAppHandoffV2FundingIdempotencyKey(input.handoffId),
      ],
    );
    if (!operation.rows[0]) {
      throw new TelegramAppHandoffV2Error(
        "trade_intent_changed",
        "handoff funding operation no longer has its exact ownership binding",
      );
    }
    return {
      fundingOperationId: intent.funding_operation_id,
      handoffId: input.handoffId,
      kind: "client_execution_required",
      requiredContractVersion:
        TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
    };
  }
  const committed = await input.runtime.commitPreparedInTransaction(
    client,
    input.prepared,
  );
  const linked = await client.query(
    `update telegram_trade_intents intent
        set status = 'funding',
            funding_operation_id = $3::uuid,
            expires_at = greatest(
              intent.expires_at,
              clock_timestamp() + interval '30 minutes'
            ),
            result = coalesce(intent.result, '{}'::jsonb) || jsonb_build_object(
              'appHandoffFunding',
              jsonb_build_object(
                'handoffId', $4::uuid,
                'operationId', $3::uuid,
                'version', 2
              )
            ),
            updated_at = clock_timestamp()
      where intent.id = $1::uuid
        and intent.user_id = $2::uuid
        and intent.delivery_mode = 'app_handoff'
        and intent.action = 'buy'
        and intent.funding_operation_id is null
        and intent.status in ('previewed', 'confirming', 'external_handoff')`,
    [
      input.tradeIntentId,
      input.userId,
      committed.operation.id,
      input.handoffId,
    ],
  );
  if ((linked.rowCount ?? 0) !== 1) {
    throw new TelegramAppHandoffV2Error(
      "trade_intent_changed",
      "trade intent changed while attaching funding operation",
    );
  }
  return {
    fundingOperationId: committed.operation.id,
    handoffId: input.handoffId,
    kind: "client_execution_required",
    requiredContractVersion: TELEGRAM_APP_HANDOFF_V2_EXECUTION_CONTRACT_VERSION,
  };
}

